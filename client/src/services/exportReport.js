/**
 * Utilities for exporting professional audit reports.
 */

export function printAnalysisReport() {
  window.print();
}

export function downloadAnalysisMarkdown(analysis) {
  if (!analysis) return;

  const candidate = analysis.candidate || {};
  const dateStr = new Date(analysis.analyzedAt || Date.now()).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  let report = `# RESUMEAI - COMPREHENSIVE RESUME & ATS AUDIT REPORT
Generated on: ${dateStr}
File Analyzed: ${analysis.fileName || 'Resume Document'}
Engine Mode: ${analysis.isDemoMode ? 'Intelligent Local NLP (Demo Mode)' : 'OpenAI GPT-4o-mini'}

============================================================
EXECUTIVE SUMMARY
============================================================
Candidate Name:    ${candidate.name || 'Candidate'}
Email:             ${candidate.email || 'Not detected'}
Phone:             ${candidate.phone || 'Not detected'}
LinkedIn:          ${candidate.linkedin || 'Not detected'}
GitHub:            ${candidate.github || 'Not detected'}

OVERALL SCORE:     ${analysis.overallScore} / 100
ATS Score:         ${analysis.atsScore} / 100
Job Match:         ${analysis.jobMatchScore} / 100
Skills Match:      ${analysis.skillsMatch} / 100
Keyword Match:     ${analysis.keywordMatch} / 100

============================================================
KEY FINDINGS & STRENGTHS
============================================================
${(analysis.strengths || []).map((s) => `[+] ${s}`).join('\n')}

============================================================
CRITICAL AREAS FOR IMPROVEMENT
============================================================
${(analysis.weaknesses || []).map((w) => `[-] ${w}`).join('\n')}

============================================================
SKILLS ANALYSIS
============================================================
* Matching Skills (${(analysis.matchingSkills || []).length}):
  ${(analysis.matchingSkills || []).join(', ') || 'None'}

* Missing High-Impact Skills (${(analysis.missingSkills || []).length}):
  ${(analysis.missingSkills || []).join(', ') || 'None identified'}

* Extracted Candidate Skills:
  ${(candidate.skills || []).join(', ') || 'None'}

============================================================
KEYWORD COVERAGE
============================================================
* Matched Keywords:   ${(analysis.matchingKeywords || []).join(', ') || 'N/A'}
* Missing Keywords:   ${(analysis.missingKeywords || []).join(', ') || 'N/A'}
* Important JD Terms: ${(analysis.importantKeywords || []).join(', ') || 'N/A'}

============================================================
SECTION-BY-SECTION BREAKDOWN
============================================================
${Object.entries(analysis.sectionAnalysis || {})
  .map(([sectionName, data]) => {
    return `### ${sectionName.toUpperCase()} (Score: ${data.score}/100)
- Positives: ${data.good && data.good.length > 0 ? data.good.join('; ') : 'Needs attention'}
- Recommendations: ${data.improvements && data.improvements.length > 0 ? data.improvements.join('; ') : 'No urgent changes needed'}`;
  })
  .join('\n\n')}

============================================================
PRIORITIZED ACTIONABLE AI RECOMMENDATIONS
============================================================
${(analysis.recommendations || [])
  .map((rec, i) => {
    return `${i + 1}. [${rec.priority.toUpperCase()} PRIORITY] ${rec.title}
   Details: ${rec.description}
   ${rec.example ? `Example: ${rec.example}` : ''}`;
  })
  .join('\n\n')}

------------------------------------------------------------
Report generated by ResumeAI - Production-Grade Career Intelligence.
`;

  const blob = new Blob([report], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute(
    'download',
    `ResumeAI_Audit_${(candidate.name || 'Candidate').replace(/\s+/g, '_')}_${Date.now()}.md`
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadAnalysisJson(analysis) {
  if (!analysis) return;
  const candidate = analysis.candidate || {};
  const jsonStr = JSON.stringify(analysis, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute(
    'download',
    `ResumeAI_Data_${(candidate.name || 'Candidate').replace(/\s+/g, '_')}_${Date.now()}.json`
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export async function copyAnalysisSummaryToClipboard(analysis) {
  if (!analysis) return false;
  const candidate = analysis.candidate || {};
  const summary = `ResumeAI Audit Summary for ${candidate.name || 'Candidate'}
Overall Score: ${analysis.overallScore}/100
ATS Compatibility: ${analysis.atsScore}%
Job Match: ${analysis.jobMatchScore}%
Skills Match: ${analysis.skillsMatch}%
Top Strengths: ${(analysis.strengths || []).slice(0, 3).join('; ')}
Top Skill Gaps: ${(analysis.missingSkills || []).slice(0, 4).join(', ') || 'None identified'}
Report generated by ResumeAI`;

  if (navigator.clipboard && navigator.clipboard.writeText) {
    await navigator.clipboard.writeText(summary);
    return true;
  }
  return false;
}
